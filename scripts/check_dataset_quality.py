#!/usr/bin/env python3
"""Quality gate checker for Interview Copilot SFT datasets."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from training_common import (
    contains_first_person,
    critical_failure_tags,
    extract_tokens,
    parse_json,
    parse_jsonl,
    safe_float,
    word_count,
    write_json,
)


def assistant_text(row: dict[str, Any]) -> str:
    for message in row.get("messages") or []:
        if isinstance(message, dict) and message.get("role") == "assistant":
            return str(message.get("content") or "").strip()
    return ""


def main() -> int:
    parser = argparse.ArgumentParser(description="Check dataset quality gates before LoRA training.")
    parser.add_argument(
        "--dataset-report",
        default="artifacts/finetune/interview_dataset_report.v2.json",
        help="Path to dataset report JSON generated by build_finetune_dataset.py",
    )
    parser.add_argument(
        "--dataset-jsonl",
        default="artifacts/finetune/interview_train.sft.v2.jsonl",
        help="Path to canonical train JSONL file.",
    )
    parser.add_argument(
        "--output",
        default="artifacts/finetune/interview_quality_report.v2.json",
        help="Output quality report path.",
    )
    parser.add_argument("--min-train-records", type=int, default=1500)
    parser.add_argument("--min-web-ratio", type=float, default=0.70)
    parser.add_argument("--max-glossary-ratio", type=float, default=0.25)
    parser.add_argument("--min-ai-mlops-ratio", type=float, default=0.20)
    parser.add_argument("--min-behavioral-ratio", type=float, default=0.10)
    parser.add_argument("--max-behavioral-ratio", type=float, default=0.20)
    parser.add_argument("--min-average-quality", type=float, default=0.52)
    parser.add_argument("--min-first-person-compliance", type=float, default=0.95)
    parser.add_argument("--min-speakable-ratio", type=float, default=0.90)
    parser.add_argument("--min-candidate-grounded-ratio", type=float, default=0.80)
    parser.add_argument("--max-critical-failure-rate", type=float, default=0.03)
    parser.add_argument("--max-near-duplicate-ratio", type=float, default=0.03)
    args = parser.parse_args()

    dataset_report_path = Path(args.dataset_report).resolve()
    dataset_path = Path(args.dataset_jsonl).resolve()
    output_path = Path(args.output).resolve()

    blocked_reasons: list[str] = []
    warnings: list[str] = []

    if not dataset_report_path.exists():
        blocked_reasons.append("dataset_report_missing")
        dataset_report: dict[str, Any] = {}
    else:
        try:
            dataset_report = parse_json(dataset_report_path)
        except Exception as exc:
            blocked_reasons.append("dataset_report_invalid")
            warnings.append(str(exc))
            dataset_report = {}

    rows = parse_jsonl(dataset_path)
    if not rows:
        blocked_reasons.append("dataset_jsonl_missing_or_empty")

    source_ratio_final = dataset_report.get("source_ratio_final") if isinstance(dataset_report, dict) else {}
    category_ratio_final = dataset_report.get("category_ratio_final") if isinstance(dataset_report, dict) else {}
    quality_metrics = dataset_report.get("quality_metrics") if isinstance(dataset_report, dict) else {}
    dropped_counter = dataset_report.get("dropped_counter") if isinstance(dataset_report, dict) else {}

    records_train = int(dataset_report.get("records_train") or len(rows)) if isinstance(dataset_report, dict) else len(rows)
    records_total = int(dataset_report.get("records_total") or len(rows)) if isinstance(dataset_report, dict) else len(rows)
    web_ratio = safe_float(source_ratio_final.get("web_corpus") if isinstance(source_ratio_final, dict) else 0.0)
    glossary_ratio = safe_float(source_ratio_final.get("glossary") if isinstance(source_ratio_final, dict) else 0.0)
    ai_mlops_ratio = safe_float(category_ratio_final.get("ai_mlops") if isinstance(category_ratio_final, dict) else 0.0)
    behavioral_ratio = safe_float(
        category_ratio_final.get("behavioral_interview") if isinstance(category_ratio_final, dict) else 0.0
    )
    average_quality = safe_float(quality_metrics.get("average_quality") if isinstance(quality_metrics, dict) else 0.0)
    first_person_compliance = safe_float(
        quality_metrics.get("first_person_compliance") if isinstance(quality_metrics, dict) else 0.0
    )
    speakable_ratio = safe_float(quality_metrics.get("speakable_answer_ratio") if isinstance(quality_metrics, dict) else 0.0)
    candidate_grounded_ratio = safe_float(
        quality_metrics.get("candidate_specific_grounded_ratio") if isinstance(quality_metrics, dict) else 0.0
    )
    critical_failure_rate = safe_float(
        quality_metrics.get("critical_failure_rate") if isinstance(quality_metrics, dict) else 1.0
    )

    if rows:
        fingerprints: set[str] = set()
        duplicate_count = 0
        first_person_count = 0
        speakable_count = 0
        failure_rows = 0
        quality_sum = 0.0
        candidate_specific_total = 0
        candidate_specific_grounded = 0
        for row in rows:
            answer = assistant_text(row)
            metadata = row.get("metadata") or {}
            fingerprint = "|".join(sorted(extract_tokens(answer)))[:1000]
            if fingerprint in fingerprints:
                duplicate_count += 1
            else:
                fingerprints.add(fingerprint)
            failures = critical_failure_tags(answer)
            if failures:
                failure_rows += 1
            if contains_first_person(answer):
                first_person_count += 1
            if not failures and 45 <= word_count(answer) <= 140:
                speakable_count += 1
            quality_sum += safe_float(metadata.get("quality_score"), 0.0)
            if bool(metadata.get("candidate_specific")):
                candidate_specific_total += 1
                if safe_float(metadata.get("quality_score"), 0.0) >= 0.6:
                    candidate_specific_grounded += 1

        near_duplicate_ratio = duplicate_count / max(1, len(rows))
        if not average_quality:
            average_quality = quality_sum / max(1, len(rows))
        if not first_person_compliance:
            first_person_compliance = first_person_count / max(1, len(rows))
        if not speakable_ratio:
            speakable_ratio = speakable_count / max(1, len(rows))
        if critical_failure_rate >= 1.0:
            critical_failure_rate = failure_rows / max(1, len(rows))
        if candidate_specific_total > 0 and not candidate_grounded_ratio:
            candidate_grounded_ratio = candidate_specific_grounded / max(1, candidate_specific_total)
        if candidate_specific_total == 0 and not candidate_grounded_ratio:
            candidate_grounded_ratio = 1.0
    else:
        near_duplicate_ratio = 1.0

    duplicate_dropped = int(dropped_counter.get("duplicate") or 0) if isinstance(dropped_counter, dict) else 0
    if duplicate_dropped and len(rows):
        near_duplicate_ratio = max(near_duplicate_ratio, duplicate_dropped / max(1, duplicate_dropped + len(rows)))

    dataset_blocked = bool(dataset_report.get("blocked")) if isinstance(dataset_report, dict) else True
    if dataset_blocked:
        blocked_reasons.append("dataset_report_blocked")

    if records_train < int(args.min_train_records):
        blocked_reasons.append("train_records_below_min")
    if web_ratio < float(args.min_web_ratio):
        blocked_reasons.append("web_ratio_below_min")
    if glossary_ratio > float(args.max_glossary_ratio) + 1e-9:
        blocked_reasons.append("glossary_ratio_above_max")
    if ai_mlops_ratio < float(args.min_ai_mlops_ratio):
        blocked_reasons.append("ai_mlops_ratio_below_min")
    if behavioral_ratio < float(args.min_behavioral_ratio):
        blocked_reasons.append("behavioral_ratio_below_min")
    if behavioral_ratio > float(args.max_behavioral_ratio) + 1e-9:
        blocked_reasons.append("behavioral_ratio_above_max")
    if average_quality < float(args.min_average_quality):
        blocked_reasons.append("average_quality_below_min")
    if first_person_compliance < float(args.min_first_person_compliance):
        blocked_reasons.append("first_person_compliance_below_min")
    if speakable_ratio < float(args.min_speakable_ratio):
        blocked_reasons.append("speakable_ratio_below_min")
    if candidate_grounded_ratio < float(args.min_candidate_grounded_ratio):
        blocked_reasons.append("candidate_grounded_ratio_below_min")
    if critical_failure_rate > float(args.max_critical_failure_rate) + 1e-9:
        blocked_reasons.append("critical_failure_rate_above_max")
    if near_duplicate_ratio > float(args.max_near_duplicate_ratio) + 1e-9:
        blocked_reasons.append("near_duplicate_ratio_above_max")

    blocked = len(blocked_reasons) > 0

    quality_report = {
        "ok": True,
        "schema_version": "quality.v2",
        "blocked": blocked,
        "blocked_reasons": blocked_reasons,
        "warnings": warnings,
        "inputs": {
            "dataset_report": str(dataset_report_path),
            "dataset_jsonl": str(dataset_path),
        },
        "metrics": {
            "records_train": records_train,
            "records_total": records_total,
            "web_ratio": round(web_ratio, 4),
            "glossary_ratio": round(glossary_ratio, 4),
            "ai_mlops_ratio": round(ai_mlops_ratio, 4),
            "behavioral_ratio": round(behavioral_ratio, 4),
            "average_quality": round(average_quality, 4),
            "first_person_compliance": round(first_person_compliance, 4),
            "speakable_ratio": round(speakable_ratio, 4),
            "candidate_grounded_ratio": round(candidate_grounded_ratio, 4),
            "critical_failure_rate": round(critical_failure_rate, 6),
            "near_duplicate_ratio": round(near_duplicate_ratio, 6),
            "dataset_rows": len(rows),
        },
        "thresholds": {
            "min_train_records": int(args.min_train_records),
            "min_web_ratio": float(args.min_web_ratio),
            "max_glossary_ratio": float(args.max_glossary_ratio),
            "min_ai_mlops_ratio": float(args.min_ai_mlops_ratio),
            "min_behavioral_ratio": float(args.min_behavioral_ratio),
            "max_behavioral_ratio": float(args.max_behavioral_ratio),
            "min_average_quality": float(args.min_average_quality),
            "min_first_person_compliance": float(args.min_first_person_compliance),
            "min_speakable_ratio": float(args.min_speakable_ratio),
            "min_candidate_grounded_ratio": float(args.min_candidate_grounded_ratio),
            "max_critical_failure_rate": float(args.max_critical_failure_rate),
            "max_near_duplicate_ratio": float(args.max_near_duplicate_ratio),
        },
        "manual_sampling": {
            "required": True,
            "sample_size": 60,
            "buckets": {
                "technical": 30,
                "ai_mlops": 15,
                "behavioral": 15,
            },
            "pass_rule": "average_score_gte_4_of_5_and_critical_error_rate_lt_0.03",
        },
    }
    write_json(output_path, quality_report)

    print(
        json.dumps(
            {
                "ok": True,
                "blocked": blocked,
                "blocked_reasons": blocked_reasons,
                "output": str(output_path),
                "metrics": quality_report["metrics"],
            },
            ensure_ascii=False,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
